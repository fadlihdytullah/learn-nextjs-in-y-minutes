function lineCells(text: string, top: number) {
  const cells: [number, number][] = [];
  let x = 0;
  for (const ch of text.toLowerCase()) {
    const g = glyphs[ch];
    if (!g) throw new Error(`PixelTitle: no glyph for "${ch}"`);
    g.forEach((row, y) =>
      [...row].forEach((c, dx) => {
        if (c === "#") cells.push([x + dx, top + y]);
      }),
    );
    x += g[0].length + 1;
  }
  return { cells, width: x - 1 };
}

export default function PixelTitle({ lines, label }: { lines: string[]; label: string }) {
  const rendered = lines.map((l, i) => lineCells(l, i * 8));
  const width = Math.max(...rendered.map((r) => r.width));
  const height = lines.length * 8 - 1;
  return (
    <h1 className="pixel-title">
      <svg viewBox={`0 0 ${width} ${height}`} role="img" aria-label={label}>
        <defs>
          <linearGradient id="pixel-ink" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2={height}>
            <stop offset="0" stopColor="var(--fg)" />
            <stop offset="1" stopColor="var(--fg-muted)" />
          </linearGradient>
        </defs>
        <g fill="url(#pixel-ink)">
          {rendered.flatMap((r) => r.cells).map(([x, y]) => (
            <rect key={`${x}-${y}`} x={x + 0.08} y={y + 0.08} width={0.84} height={0.84} rx={0.24} />
          ))}
        </g>
      </svg>
    </h1>
  );
}
